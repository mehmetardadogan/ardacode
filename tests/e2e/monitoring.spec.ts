import { test, expect } from '@playwright/test';

test('consented visit, provider outcomes, protected polling and export', async ({ browser, page }, testInfo) => {
    const browserErrors: string[] = [];
    page.on('pageerror', e => browserErrors.push(e.message));
    const receipts: Record<string, unknown>[] = [];
    page.on('request', request => { if (request.url().endsWith('/izleme/olay')) receipts.push(request.postDataJSON()); });
    await page.goto('/');
    await expect(page.getByRole('heading', { name: 'Ziyaret ölçümüne izin verir misiniz?' })).toBeVisible();
    await page.waitForTimeout(800);
    expect(receipts).toHaveLength(0);
    await page.getByRole('button', { name: 'İzin verme', exact: true }).click();
    await page.waitForTimeout(700);
    expect(receipts).toHaveLength(0);
    await page.getByRole('button', { name: 'Gizlilik tercihleri' }).click();
    await page.getByRole('button', { name: 'İzin ver', exact: true }).click();
    await expect.poll(() => receipts.length).toBeGreaterThan(0);
    await page.locator('#hizmetler').scrollIntoViewIfNeeded();
    await page.locator('#hizmetler').getByRole('button', { name: 'Detayları İncele' }).first().click();
    await page.keyboard.press('Escape');
    await page.route('https://formspree.io/f/xaeeqjdq', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{"ok":true}' }));
    const form = page.locator('#iletisim');
    await form.scrollIntoViewIfNeeded();
    await form.locator('input').nth(0).fill('E2E local only');
    await form.locator('input').nth(1).fill('test@example.invalid');
    await form.locator('textarea').fill('Local test message never sent to the real provider.');
    await form.locator('input[type="checkbox"]').check();
    await form.getByRole('button', { name: 'Mesajı Gönder (Formspree)' }).click();
    await expect(form.getByText('Formspree mesajınızı kabul etti.', { exact: false })).toBeVisible();
    await page.unroute('https://formspree.io/f/xaeeqjdq');
    await page.route('https://formspree.io/f/xaeeqjdq', route => route.fulfill({ status: 422, contentType: 'application/json', body: '{"errors":[{"message":"Local test validation failure"}]}' }));
    await form.locator('input').nth(0).fill('E2E local only');
    await form.locator('input').nth(1).fill('test@example.invalid');
    await form.locator('textarea').fill('Local rejected message never sent to the real provider.');
    await form.locator('input[type="checkbox"]').check();
    await form.getByRole('button', { name: 'Mesajı Gönder (Formspree)' }).click();
    await expect(form.getByText('Local test validation failure')).toBeVisible();
    await page.waitForTimeout(700);
    const allPayloads = JSON.stringify(receipts);
    expect(allPayloads).not.toContain('test@example.invalid');
    expect(allPayloads).not.toContain('never sent');
    const guest = await page.request.get('/admin/izleme/events', { headers: { Accept: 'application/json' } });
    expect(guest.status()).toBe(401);

    const adminContext = await browser.newContext({ baseURL: testInfo.project.use.baseURL, viewport: { width: 1440, height: 1000 } });
    const admin = await adminContext.newPage();
    admin.on('pageerror', e => browserErrors.push(e.message));
    await admin.goto('/admin/login');
    await admin.locator('input[type="email"]').fill('mehmetardad068@gmail.com');
    await admin.locator('input[type="password"]').fill(process.env.MONITORING_E2E_PASSWORD || 'local-monitor-test-only');
    await admin.getByRole('button', { name: 'Giriş Yap', exact: true }).click();
    await expect(admin).toHaveURL(/\/admin$/);
    await admin.getByRole('link', { name: 'Canlı Log Merkezi', exact: true }).click();
    await expect(admin.getByRole('heading', { name: 'Canlı Log Merkezi' })).toBeVisible();
    await expect(admin.getByText('8 sn aralıkla bağlı')).toBeVisible();
    await expect(admin.getByRole('button', { name: /Olay .*Sayfa görüntülendi/ }).first()).toBeVisible();
    const stats = await (await admin.request.get('/admin/izleme/events')).json();
    expect(stats.stats.form_accepted).toBeGreaterThanOrEqual(1);
    expect(stats.stats.form_failed).toBeGreaterThanOrEqual(1);
    expect(stats.stats.form_archived).toBeGreaterThanOrEqual(1);
    expect(stats.stats.page_views).toBeGreaterThanOrEqual(1);
    await admin.getByRole('button', { name: 'Duraklat', exact: true }).click();
    await expect(admin.getByText('Akış duraklatıldı')).toBeVisible();
    await admin.getByRole('button', { name: 'Devam et', exact: true }).click();
    await admin.getByLabel('Seviye', { exact: true }).selectOption('ERROR');
    await expect(admin.getByRole('button', { name: /Olay .*Formspree gönderimi başarısız/ }).first()).toBeVisible();
    await admin.getByRole('button', { name: /Olay .*Formspree gönderimi başarısız/ }).first().click();
    await expect(admin.getByRole('complementary', { name: 'Tekil olay ayrıntısı' })).toBeVisible();
    await admin.getByLabel('İnceleme durumu').selectOption('investigating');
    await expect(admin.getByLabel('İnceleme durumu')).toHaveValue('investigating');
    await admin.getByRole('button', { name: 'Ayrıntıyı kapat' }).click();
    await admin.getByRole('button', { name: 'Temizle', exact: true }).click();
    await admin.getByRole('link', { name: 'Güvenlik İzleme', exact: true }).click();
    await expect(admin.getByLabel('Kategori', { exact: true })).toHaveValue('security');
    await admin.getByRole('link', { name: 'Canlı Log Merkezi', exact: true }).click();
    await expect(admin.getByLabel('Kategori', { exact: true })).toHaveValue('');
    const newest = (await (await admin.request.get('/admin/izleme/events')).json()).events;
    const [firstEvent, secondEvent] = newest.slice(0, 2);
    await admin.getByRole('button', { name: 'Şimdi yenile' }).click();
    await admin.route(`**/admin/izleme/events/${firstEvent.id}`, async route => {
        if (route.request().method() === 'GET') {
            await new Promise(resolve => setTimeout(resolve, 700));
            await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(firstEvent) }).catch(() => {});
        } else await route.continue();
    });
    await admin.getByRole('button', { name: new RegExp(`^Olay ${firstEvent.id}:`) }).click();
    await admin.getByRole('button', { name: new RegExp(`^Olay ${secondEvent.id}:`) }).click();
    await expect(admin.getByRole('complementary').getByRole('heading', { name: `Olay #${secondEvent.id}`, exact: true })).toBeVisible();
    await admin.waitForTimeout(900);
    await expect(admin.getByRole('complementary').getByRole('heading', { name: `Olay #${secondEvent.id}`, exact: true })).toBeVisible();
    await admin.unroute(`**/admin/izleme/events/${firstEvent.id}`);
    await admin.getByRole('button', { name: 'Ayrıntıyı kapat' }).click();
    const csv = await admin.request.get('/admin/izleme/export');
    expect(csv.status()).toBe(200);
    expect(csv.headers()['content-type']).toContain('text/csv');
    const exportContent = await csv.text();
    expect(exportContent).toContain('Sayfa görüntülendi');
    expect(exportContent).not.toContain('test@example.invalid');
    await admin.screenshot({ path: testInfo.outputPath('desktop.png'), fullPage: true });
    await admin.setViewportSize({ width: 390, height: 844 });
    await admin.screenshot({ path: testInfo.outputPath('mobile.png'), fullPage: true });
    const overflow = await admin.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    expect(overflow).toBe(false);
    // A public runtime error only transmits a fixed event type, never raw text.
    await page.evaluate(() => { window.dispatchEvent(new ErrorEvent('error', { error: new Error('private-token-do-not-record'), message: 'private-token-do-not-record' })); });
    await expect.poll(async () => (await (await admin.request.get('/admin/izleme/events?category=errors')).json()).events.some((e: {event_type: string}) => e.event_type === 'javascript_error')).toBe(true);
    await page.getByRole('button', { name: 'Gizlilik tercihleri' }).click();
    await page.getByRole('button', { name: 'İzni geri al ve oturumu sil' }).click();
    await expect(page.getByRole('button', { name: 'Gizlilik tercihleri' })).toBeVisible();
    expect(browserErrors).toEqual([]);
    await adminContext.close();
});
